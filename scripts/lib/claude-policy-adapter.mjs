import {
  canonicalJsonBytes,
  sha256Bytes,
} from './governance-artifacts.mjs';
import { adapterPathFor } from './target-registry.mjs';

export const CLAUDE_POLICY_ADAPTER_VERSION = '1.0.0';

/**
 * Every value here is read off the frozen Claude Code capability matrix in
 * docs/research/2026-07-31-claude-code-policy-capability-matrix.md. Two rows
 * differ from the Codex map, and both differences are matrix rows rather than
 * judgment calls:
 *
 *   filesystem.root-write  The matrix classifies the working-directory
 *                          restriction as unsupported: additionalDirectories
 *                          only grants access, and no documented project-layer
 *                          key narrows the working directory below its default.
 *   network                BLOCKED item 1. No verified project-layer key for
 *                          network egress was located, which is exactly the
 *                          frozen definition of unsupported — "no truthful
 *                          project-local mapping or observation for this
 *                          control". Approximating it with a Bash(curl *) deny
 *                          is refused by the same matrix row.
 *
 * delete and publish stay requires-human-approval as they are for Codex. That
 * classification is a statement about the governed action needing a person, not
 * about the target's key surface; the absence of a Claude tool for either is
 * carried by materializationStatus instead.
 */
const SUPPORT = Object.freeze({
  'filesystem.project-read': 'representable-only',
  'filesystem.project-write': 'representable-only',
  'filesystem.root-write': 'unsupported',
  'shell.execution': 'requires-human-approval',
  network: 'unsupported',
  credentials: 'unsupported',
  delete: 'requires-human-approval',
  publish: 'requires-human-approval',
  'external-content': 'representable-only',
  'generated-artifacts': 'enforceable',
  'provider-retention': 'unsupported',
  verification: 'representable-only',
});

export function claudeSupportForControl(capability, mode) {
  if (
    mode === 'deny'
    && ['delete', 'publish', 'shell.execution'].includes(capability)
  ) {
    return 'representable-only';
  }
  return SUPPORT[capability] ?? 'unsupported';
}

function mappedControls(manifest) {
  return Object.values(manifest.controls)
    .flat()
    .filter((control) => control.targetSupport.claude !== 'unsupported')
    .map((control) => ({
      controlId: control.controlId,
      capability: control.capability,
      mode: control.mode,
      support: control.targetSupport.claude,
      representation: control.targetSupport.claude === 'enforceable'
        ? 'compiler-owned-artifact'
        : control.targetSupport.claude === 'requires-human-approval'
          ? 'human-approval-guidance'
          : 'guidance',
    }))
    .sort((left, right) => (
      left.controlId < right.controlId
        ? -1
        : left.controlId > right.controlId
          ? 1
          : 0
    ));
}

export function buildClaudePolicyAdapter(manifest) {
  const policyPath =
    `.agent-governance/policies/${manifest.policyId}.json`;
  const adapterPath = adapterPathFor('claude', manifest.policyId);
  return {
    schemaVersion: 1,
    target: 'claude',
    adapterVersion: CLAUDE_POLICY_ADAPTER_VERSION,
    policyId: manifest.policyId,
    policyHash: sha256Bytes(canonicalJsonBytes(manifest)),
    generatedFiles: [adapterPath, policyPath].sort(),
    mappedControls: mappedControls(manifest),
    unsupportedControls: structuredClone(manifest.unsupportedControls),
    humanReviewRequired: [...manifest.humanApprovalControls].sort(),
    compatibility: {
      projectInstructions: 'CLAUDE.md',
      projectConfigGenerated: false,
      runtimeEvidenceRequired: true,
      notes: [
        'CLAUDE.md remains the canonical repository instruction owner.',
        'No .claude/settings.json is generated by compile.',
        'Workspace trust, settings precedence, and runtime behavior require separate evidence.',
      ],
    },
    repositoryInstructionRefs: ['CLAUDE.md'],
    approvalGuidance: [
      'A denied action remains denied and cannot be enabled by approval.',
      'For publish, destructive, or shell actions, require explicit human approval only when the canonical control mode requires approval.',
      'Treat approval guidance as a decision gate, not evidence of runtime enforcement.',
    ],
    verificationCommands: [],
    prohibitedActionGuidance: [
      'Do not read credentials or provider sessions.',
      'Do not write user-global or managed Claude Code settings.',
      'Do not treat this adapter as an OS sandbox or runtime attestation.',
      'Do not infer a verification command that is absent from governed project inputs.',
    ],
    ownership: {
      generator: 'GovernSeed',
      artifactType: 'claude-policy-adapter',
    },
    status: 'candidate',
  };
}
